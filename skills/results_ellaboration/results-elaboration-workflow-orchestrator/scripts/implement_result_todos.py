def replace_slots(text: str) -> str:
    for title, replacement in REPLACEMENTS.items():
        pattern = re.compile(rf"\\begin\{{slot\}}\[{re.escape(title)}\].*?\\end\{{slot\}}", re.S)
        text, count = pattern.subn(lambda _match, value=replacement.strip(): value, text)
        if count != 1:
            raise SystemExit(f"expected exactly one slot for {title!r}, replaced {count}")
    text = text.replace(
        "This section records the missing QFT data that would turn the finite theorem into a complete Wilson-block application.  The slots are written as future theorem/proposition placeholders so that the final paper can expand by replacing each slot with a proof or computation.  They are not assumptions used in Theorem \\ref{thm:finite-certificate}.",
        "This section implements the result-expansion obligations needed to turn the finite theorem into a controlled Wilson-block application template.  The replacements below separate proved finite facts, same-theory certificates, coefficient-conversion theorems, and regulator-specific obligations that remain conditional.  They are not assumptions used in Theorem \\ref{thm:finite-certificate}.",
    )
    text = text.replace(
        "A final three-hairpin Wilson section should contain the following data.",
        "A regulator-specific three-hairpin Wilson section must eventually contain the following data.  The present implementation supplies an exact finite coefficient model and marks the remaining Wilson-path derivation boundary.",
    )
    text = text.replace(
        "The next result-bearing expansion is not more narrative: it is the completion of Slots \\ref{slot:regulator-observable}--\\ref{slot:uniform-remainder}, preferably for one explicit three-hairpin Wilson block.",
        "The result-bearing expansion implemented here replaces the slots by finite certificates, coefficient-conversion theorems, an exact three-observable Schur--Feshbach model, and explicit demotion boundaries.  A future regulator-specific Wilson calculation must still derive the same coefficient data from named Wilson paths.",
    )
    endpoint_sentence = (
        "The remaining regulator-specific QFT work is exactly the content bounded by Propositions "
        r"\ref{prop:endpoint-prefactor} and \ref{prop:uniform-endpoint-remainder}: define \(Z_v\), "
        "derive the prefactor, compute incidence data, and bound the tails in the same regulator."
    )
    text = re.sub(
        r"The missing QFT work is exactly Slots \\ref\{slot:color-factor\} and \\ref\{slot:uniform-remainder\}: define \\?\(Z_v\\?\), derive the prefactor, compute incidence data, and bound the tails\.",
        lambda _match: endpoint_sentence,
        text,
    )
    text = re.sub(r"^\\newtheorem\{slot\}\[theorem\]\{Result expansion slot\}\n", "", text, flags=re.M)
    return text


def render_status_markdown() -> str:
    lines = [
        "# Result TODO Implementation Status",
        "",
        "All eight result-elaboration TODOs were implemented into the expanded manuscript draft.",
        "Where the original draft lacked regulator-specific Wilson data, the implementation uses a rigorous finite certificate and records the residual claim boundary instead of promoting an unsupported Wilson result.",
        "",
        "## Status",
        "",
    ]
    for item in STATUS:
        lines.extend(
            [
                f"### {item['todo_id']} `{item['source_marker']}`",
                "",
                f"- Status: `{item['status']}`",
                f"- Artifact: {item['artifact']}",
                f"- Residual boundary: {item['residual_boundary']}",
                "",
            ]
        )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("draft", type=Path)
    args = parser.parse_args()
    draft_path = args.draft.expanduser().resolve()
    text = draft_path.read_text(encoding="utf-8")
    expanded = replace_slots(text)
    if "\\begin{slot}" in expanded or "\\end{slot}" in expanded:
        raise SystemExit("expanded draft still contains slot environments")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    tex_path = OUT_DIR / "finite_wilson_os_schur_feshbach_paper_todos_implemented.tex"
    status_json = OUT_DIR / "todo_implementation_status.json"
    status_md = OUT_DIR / "todo_implementation_status.md"

    tex_path.write_text(expanded, encoding="utf-8")
    status_json.write_text(json.dumps({"schema": "abducer.results_elaboration.todo_implementation.v1", "items": STATUS}, indent=2), encoding="utf-8")
    status_md.write_text(render_status_markdown(), encoding="utf-8")

    print(f"Wrote {tex_path}")
    print(f"Wrote {status_json}")
    print(f"Wrote {status_md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
