"""Deterministic, non-following source-tree fingerprints."""

from __future__ import annotations

import fnmatch
import hashlib
import os
import stat
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable

from .jsonio import canonical_bytes
from .paths import canonical_path


class FingerprintError(RuntimeError):
    """Raised when a stable fingerprint cannot be obtained."""


@dataclass(frozen=True, slots=True)
class IgnoreRule:
    pattern: str
    reason: str

    def to_dict(self) -> dict[str, str]:
        return {"pattern": self.pattern, "reason": self.reason}


DEFAULT_IGNORE_RULES: tuple[IgnoreRule, ...] = (
    IgnoreRule(".git", "version-control internals"),
    IgnoreRule(".git/**", "version-control internals"),
    IgnoreRule(".hg", "version-control internals"),
    IgnoreRule(".hg/**", "version-control internals"),
    IgnoreRule(".svn", "version-control internals"),
    IgnoreRule(".svn/**", "version-control internals"),
    IgnoreRule("node_modules", "dependency cache"),
    IgnoreRule("node_modules/**", "dependency cache"),
    IgnoreRule("**/node_modules", "dependency cache"),
    IgnoreRule("**/node_modules/**", "dependency cache"),
    IgnoreRule(".venv", "dependency environment"),
    IgnoreRule(".venv/**", "dependency environment"),
    IgnoreRule("venv", "dependency environment"),
    IgnoreRule("venv/**", "dependency environment"),
    IgnoreRule("__pycache__", "generated bytecode"),
    IgnoreRule("**/__pycache__", "generated bytecode"),
    IgnoreRule("**/__pycache__/**", "generated bytecode"),
    IgnoreRule("*.pyc", "generated bytecode"),
    IgnoreRule("**/*.pyc", "generated bytecode"),
    IgnoreRule(".pytest_cache", "test cache"),
    IgnoreRule("**/.pytest_cache", "test cache"),
    IgnoreRule("**/.pytest_cache/**", "test cache"),
    IgnoreRule(".ruff_cache", "lint cache"),
    IgnoreRule("**/.ruff_cache", "lint cache"),
    IgnoreRule("**/.ruff_cache/**", "lint cache"),
    IgnoreRule(".mypy_cache", "type-check cache"),
    IgnoreRule("**/.mypy_cache", "type-check cache"),
    IgnoreRule("**/.mypy_cache/**", "type-check cache"),
)


@dataclass(frozen=True, slots=True)
class FingerprintEntry:
    path: str
    type: str
    executable: bool
    digest: str | None = None
    symlink_target: str | None = None

    def to_dict(self) -> dict[str, Any]:
        result: dict[str, Any] = {
            "executable": self.executable,
            "path": self.path,
            "type": self.type,
        }
        if self.digest is not None:
            result["digest"] = self.digest
        if self.symlink_target is not None:
            result["symlink_target"] = self.symlink_target
        return result

    @classmethod
    def from_dict(cls, value: dict[str, Any]) -> "FingerprintEntry":
        return cls(
            path=value["path"],
            type=value["type"],
            executable=bool(value["executable"]),
            digest=value.get("digest"),
            symlink_target=value.get("symlink_target"),
        )


@dataclass(frozen=True, slots=True)
class TreeFingerprint:
    digest: str
    entries: tuple[FingerprintEntry, ...]
    ignore_rules: tuple[IgnoreRule, ...]
    policy: dict[str, str]

    def to_dict(self, *, include_entries: bool = True) -> dict[str, Any]:
        result: dict[str, Any] = {
            "algorithm": "sha256",
            "digest": self.digest,
            "ignore_rules": [rule.to_dict() for rule in self.ignore_rules],
            "policy": dict(sorted(self.policy.items())),
        }
        if include_entries:
            result["entries"] = [entry.to_dict() for entry in self.entries]
        return result

    @classmethod
    def from_dict(cls, value: dict[str, Any]) -> "TreeFingerprint":
        return cls(
            digest=value["digest"],
            entries=tuple(
                FingerprintEntry.from_dict(entry) for entry in value.get("entries", [])
            ),
            ignore_rules=tuple(
                IgnoreRule(rule["pattern"], rule["reason"])
                for rule in value.get("ignore_rules", [])
            ),
            policy=dict(value.get("policy", {})),
        )

    def diff(self, other: "TreeFingerprint") -> list[str]:
        left = {entry.path: entry for entry in self.entries}
        right = {entry.path: entry for entry in other.entries}
        changes = [f"removed:{path}" for path in sorted(left.keys() - right.keys())]
        changes += [f"added:{path}" for path in sorted(right.keys() - left.keys())]
        changes += [
            f"changed:{path}"
            for path in sorted(left.keys() & right.keys())
            if left[path] != right[path]
        ]
        if not changes and self.digest != other.digest:
            changes.append("fingerprint-policy-changed")
        return changes


FINGERPRINT_POLICY = {
    "concurrent_changes": "fail",
    "directories": "included",
    "file_content": "sha256",
    "mtimes": "ignored",
    "special_files": "metadata-only",
    "symlinks": "target-text-only-never-followed",
    "unix_executable_mode": "included",
    "xattrs": "ignored",
}


def _ignored(relative_path: str, rules: Iterable[IgnoreRule]) -> bool:
    return any(fnmatch.fnmatchcase(relative_path, rule.pattern) for rule in rules)


def _file_digest(path: Path, before: os.stat_result) -> str:
    digest = hashlib.sha256()
    try:
        with path.open("rb", buffering=0) as stream:
            while chunk := stream.read(1024 * 1024):
                digest.update(chunk)
        after = path.stat(follow_symlinks=False)
    except OSError as exc:
        raise FingerprintError(f"cannot fingerprint {path.name!r}: {exc}") from exc
    identity_before = (before.st_dev, before.st_ino, before.st_size, before.st_mtime_ns)
    identity_after = (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns)
    if identity_before != identity_after or not stat.S_ISREG(after.st_mode):
        raise FingerprintError(f"source changed while reading {path.name!r}")
    return f"sha256:{digest.hexdigest()}"


def fingerprint_tree(
    root: str | os.PathLike[str],
    *,
    ignore_rules: Iterable[IgnoreRule] | None = None,
) -> TreeFingerprint:
    """Fingerprint a tree without executing content or following symlinks."""

    base = canonical_path(root, must_exist=True)
    if not base.is_dir():
        raise FingerprintError("fingerprint root must be a directory")
    rules = tuple(DEFAULT_IGNORE_RULES if ignore_rules is None else ignore_rules)
    entries: list[FingerprintEntry] = []

    def walk(directory: Path, prefix: str = "") -> None:
        try:
            children = sorted(os.scandir(directory), key=lambda item: item.name)
        except OSError as exc:
            raise FingerprintError(f"cannot scan source directory: {exc}") from exc
        for child in children:
            relative = f"{prefix}/{child.name}" if prefix else child.name
            if _ignored(relative, rules):
                continue
            try:
                metadata = child.stat(follow_symlinks=False)
            except OSError as exc:
                raise FingerprintError(f"cannot stat {relative!r}: {exc}") from exc
            executable = bool(metadata.st_mode & 0o111)
            if stat.S_ISLNK(metadata.st_mode):
                try:
                    target = os.readlink(child.path)
                except OSError as exc:
                    raise FingerprintError(
                        f"cannot read symlink {relative!r}: {exc}"
                    ) from exc
                entries.append(
                    FingerprintEntry(
                        relative, "symlink", executable, symlink_target=target
                    )
                )
            elif stat.S_ISDIR(metadata.st_mode):
                entries.append(FingerprintEntry(relative, "directory", executable))
                walk(Path(child.path), relative)
            elif stat.S_ISREG(metadata.st_mode):
                entries.append(
                    FingerprintEntry(
                        relative,
                        "file",
                        executable,
                        digest=_file_digest(Path(child.path), metadata),
                    )
                )
            else:
                entry_type = (
                    "socket"
                    if stat.S_ISSOCK(metadata.st_mode)
                    else "fifo"
                    if stat.S_ISFIFO(metadata.st_mode)
                    else "device"
                    if stat.S_ISCHR(metadata.st_mode) or stat.S_ISBLK(metadata.st_mode)
                    else "special"
                )
                entries.append(FingerprintEntry(relative, entry_type, executable))

    walk(base)
    encoded_entries = [entry.to_dict() for entry in entries]
    digest = f"sha256:{hashlib.sha256(canonical_bytes({'entries': encoded_entries, 'ignore_rules': [rule.to_dict() for rule in rules], 'policy': FINGERPRINT_POLICY})).hexdigest()}"
    return TreeFingerprint(digest, tuple(entries), rules, dict(FINGERPRINT_POLICY))


tree_fingerprint = fingerprint_tree
