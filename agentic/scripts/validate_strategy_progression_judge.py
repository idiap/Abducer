"""Validate the strategy progression judge report."""

from __future__ import annotations

from agentic_common import clean_text, fail, load_json_object, rel
from build_strategy_progression_judge import JUDGE_SKILLS, OUT_JSON, OUT_MD, WINDOW_SIZE


REQUIRED_TOP_LEVEL = {
    "version",
    "generated_utc",
    "target_id",
    "judgement_id",
    "judgement_cadence",
    "window",
    "generated_by_skills",
    "evidence_sources",
    "current_strategy",
    "progression_judgement",
        "paper_contribution_readiness",
        "main_problem_alignment",
        "strategy_payoff_table",
        "novelty_high_reward_avenues",
        "validation_handoff",
    "source_artifacts",
    "epistemic_status",
}


def require_fields(row: dict, fields: list[str], context: str) -> None:
    for field in fields:
        if field not in row or (field not in {"dimension_scores", "priority_score"} and not row.get(field)):
            fail(f"{context} missing {field}")


def main() -> int:
    if not OUT_JSON.exists():
        fail(f"missing {rel(OUT_JSON)}")
    report = load_json_object(OUT_JSON)
    missing = REQUIRED_TOP_LEVEL.difference(report)
    if missing:
        fail(f"{rel(OUT_JSON)} missing {sorted(missing)}")
    if set(JUDGE_SKILLS) != set(report.get("generated_by_skills", [])):
        fail(f"{rel(OUT_JSON)} must be generated by {JUDGE_SKILLS}")
    cadence = report["judgement_cadence"]
    if int(cadence.get("total_valid_research_cycles", 0)) >= WINDOW_SIZE and not cadence.get("judgement_due"):
        fail("judgement must be due after at least 10 valid research cycles")
    window = report["window"]
    if int(window.get("window_research_cycle_count", 0)) != min(WINDOW_SIZE, int(cadence.get("total_valid_research_cycles", 0))):
        fail("window must cover the rolling latest 10 valid cycles once available")
    if len(window.get("cycle_ids", [])) != int(window.get("window_research_cycle_count", 0)):
        fail("window cycle_ids count mismatch")
    require_fields(report["current_strategy"], ["title", "active_object", "route_family"], "current_strategy")
    progress = report["progression_judgement"]
    require_fields(
        progress,
        [
            "decision",
            "payoff_potential",
            "progression_score",
            "dimension_scores",
            "summary",
            "contribution_pivot_invariant",
            "what_progressed",
            "what_did_not_progress",
            "next_decisive_test",
            "when_to_stop",
            "do_not_stop_prematurely_if",
        ],
        "progression_judgement",
    )
    for dimension in [
        "mechanistic_gain",
        "technical_specificity",
        "problem_alignment",
        "payoff_potential",
        "anti_drift_control",
        "window_learning",
    ]:
        if dimension not in progress["dimension_scores"]:
            fail(f"progression dimension missing {dimension}")
    readiness = report["paper_contribution_readiness"]
    require_fields(
        readiness,
        [
            "candidate_title",
            "smallest_honest_claim",
            "paper_contribution_type",
            "readiness_level",
            "dimension_scores",
            "novelty_argument",
            "main_problem_implication",
            "validation_burden",
            "overclaim_boundary",
            "paper_skeleton",
        ],
        "paper_contribution_readiness",
    )
    alignment = report["main_problem_alignment"]
    require_fields(
        alignment,
        [
            "alignment_class",
            "target_commitments_touched",
            "source_to_target_handoff",
            "proxy_or_transfer_risk",
            "alignment_gain",
            "alignment_loss",
            "repair_action",
            "decision_effect",
        ],
        "main_problem_alignment",
    )
    joined = clean_text(report).lower()
    for phrase in [
        "paper",
        "contribution",
        "payoff",
        "alignment",
        "validation",
        "source object",
        "target object",
    ]:
        if phrase not in joined:
            fail(f"{rel(OUT_JSON)} lacks `{phrase}`")
    if report.get("target_id") == "p-vs-np-target":
        for phrase in ["sat", "circuit", "lower bound", "certificate", "advice"]:
            if phrase not in joined:
                fail(f"{rel(OUT_JSON)} P vs NP judge lacks `{phrase}`")
        for forbidden in ["wilson", "yang-mills", "reflection positivity", "h,k wilson", "mass gap"]:
            if forbidden in joined:
                fail(f"{rel(OUT_JSON)} P vs NP judge contains cross-target term `{forbidden}`")
        avenues = report.get("novelty_high_reward_avenues", [])
        if not isinstance(avenues, list) or len(avenues) < 3:
            fail(f"{rel(OUT_JSON)} P vs NP judge needs novelty_high_reward_avenues")
    elif not any(phrase in joined for phrase in ["yang-mills", "wilson", "reflection", "spectral", "continuum"]):
        fail(f"{rel(OUT_JSON)} lacks target-specific scientific language")
    if not OUT_MD.exists():
        fail(f"missing {rel(OUT_MD)}")
    markdown = OUT_MD.read_text(encoding="utf-8")
    for phrase in ["Strategy Progression Judge", "Paper Contribution Readiness", "Contribution Pivot Invariant", "When To Stop"]:
        if phrase not in markdown:
            fail(f"{rel(OUT_MD)} missing `{phrase}`")
    pivot = clean_text(progress.get("contribution_pivot_invariant", "")).lower()
    if report.get("target_id") == "p-vs-np-target":
        for phrase in ["hardness magnification", "certificate", "advice leakage", "scientific contribution"]:
            if phrase not in pivot:
                fail(f"{rel(OUT_JSON)} P vs NP contribution pivot invariant missing `{phrase}`")
    else:
        for phrase in ["obstruction ladder", "h,k wilson collar", "finite theorem", "scientific contribution"]:
            if phrase not in pivot:
                fail(f"{rel(OUT_JSON)} contribution pivot invariant missing `{phrase}`")
    print(f"validated {rel(OUT_JSON)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
